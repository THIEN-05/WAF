func TestRequestIDIsServerGeneratedAndProblemIsMachineReadable(t *testing.T) {
	var body string
	h := RequestID(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		problem.Write(w, r, http.StatusBadRequest, "bad_request", "Bad request", "Invalid input")
	}))
	r := httptest.NewRequest(http.MethodGet, "/v1/test", nil)
	r.Header.Set("X-Request-ID", "forged\r\nX-Injected: yes")
	r.Header.Set("traceparent", "00-0123456789abcdef0123456789abcdef-0123456789abcdef-01")
	w := httptest.NewRecorder()
	h.ServeHTTP(w, r)
	body = w.Body.String()
	if w.Header().Get("X-Injected") != "" {
		t.Fatal("client request ID was reflected as a response header")
	}
	id := w.Header().Get("X-Request-ID")
	if !regexp.MustCompile(`^[0-9a-f]{32}$`).MatchString(id) || id == r.Header.Get("X-Request-ID") {
		t.Fatalf("request ID was not generated by edge: %q", id)
	}
	if w.Header().Get("Content-Type") != "application/problem+json" {
		t.Fatalf("content type=%q", w.Header().Get("Content-Type"))
	}
	var got problem.Detail
	if err := json.Unmarshal([]byte(body), &got); err != nil {
		t.Fatal(err)
	}
	if got.RequestID != id {
		t.Fatalf("problem body request ID=%q want generated ID %q", got.RequestID, id)
	}
}

func TestCSRFRequiresDoubleSubmitForCookieSession(t *testing.T) {
	next := CSRF(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusNoContent) }))
	blocked := httptest.NewRecorder()
	r := httptest.NewRequest(http.MethodPost, "/v1/tenants/x", nil)
	r.AddCookie(&http.Cookie{Name: "refresh_token", Value: "secret"})
	next.ServeHTTP(blocked, r)
	if blocked.Code != http.StatusForbidden {
		t.Fatalf("missing CSRF token status=%d", blocked.Code)
	}
	allowed := httptest.NewRecorder()
	r = httptest.NewRequest(http.MethodPost, "/v1/tenants/x", nil)
	r.AddCookie(&http.Cookie{Name: "refresh_token", Value: "secret"})
	r.AddCookie(&http.Cookie{Name: "csrf_token", Value: "csrf"})
	r.Header.Set("X-CSRF-Token", "csrf")
	next.ServeHTTP(allowed, r)
	if allowed.Code != http.StatusNoContent {
		t.Fatalf("valid CSRF token status=%d", allowed.Code)
	}
}

func TestRequestContextCarriesGeneratedRequestID(t *testing.T) {
	var got string
	h := RequestID(http.HandlerFunc(func(_ http.ResponseWriter, r *http.Request) { got = logger.RequestID(r.Context()) }))
	h.ServeHTTP(httptest.NewRecorder(), httptest.NewRequest(http.MethodGet, "/", nil))
	if !regexp.MustCompile(`^[0-9a-f]{32}$`).MatchString(got) {
		t.Fatalf("context request ID=%q", got)
	}
}
